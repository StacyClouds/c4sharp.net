namespace StacyClouds.C4Sharp
{
    /// <summary>
    /// Defines the supported element shapes available to renderers.
    /// </summary>
    public enum Shape
    {

        /// <summary>
        /// Renders a rectangular box.
        /// </summary>
        Box,
        /// <summary>
        /// Renders a rounded rectangular box.
        /// </summary>
        RoundedBox,
        /// <summary>
        /// Renders a circle.
        /// </summary>
        Circle,
        /// <summary>
        /// Renders an ellipse.
        /// </summary>
        Ellipse,
        /// <summary>
        /// Renders a hexagon.
        /// </summary>
        Hexagon,
        /// <summary>
        /// Renders a diamond.
        /// </summary>
        Diamond,
        /// <summary>
        /// Renders a cylinder, typically for data stores.
        /// </summary>
        Cylinder,
        /// <summary>
        /// Renders a pipe.
        /// </summary>
        Pipe,
        /// <summary>
        /// Renders a person silhouette.
        /// </summary>
        Person,
        /// <summary>
        /// Renders a robot silhouette.
        /// </summary>
        Robot,
        /// <summary>
        /// Renders a folder.
        /// </summary>
        Folder,
        /// <summary>
        /// Renders a web browser window.
        /// </summary>
        WebBrowser,
        /// <summary>
        /// Renders a mobile device in portrait orientation.
        /// </summary>
        MobileDevicePortrait,
        /// <summary>
        /// Renders a mobile device in landscape orientation.
        /// </summary>
        MobileDeviceLandscape,
        /// <summary>
        /// Renders the Structurizr-style component shape.
        /// </summary>
        Component

    }
}
